function make_level () {
    if (level == 1) {
        scene.setBackgroundColor(9)
        tiles.setCurrentTilemap(tilemap`level1`)
    } else if (level == 2) {
        scene.setBackgroundColor(9)
        tiles.setCurrentTilemap(tilemap`level2`)
    } else {
        game.gameOver(true)
    }
}
